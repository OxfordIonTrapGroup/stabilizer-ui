//! Transfer function estimation from exponential sine sweeps (ESS).
//!
//! The excitation is generated on the device by the `SweptSine` signal source of the
//! `dual-iir` firmware, which is added to the DAC output of a channel. As the stimulus
//! is known exactly, the responses of all streamed channels can be deconvolved with it
//! (Farina's method). In the resulting impulse responses, the harmonic distortion
//! products appear before the linear response, so that they can be separated by
//! windowing. With an integer number of cycles per harmonic delay ("synchronized" swept
//! sine, Novák et al., JAES 63, 786 (2015)), the harmonic impulse responses have a
//! well-defined phase.
//!
//! `analyse()` is called from `stabilizer_ui.transfer_function.ess.analyse()`, which
//! documents the parameters and results. Frequencies are in cycles/sample and times in
//! samples throughout. The channels (and runs) are analysed in parallel, as many at a
//! time as fit a memory budget, with the large arrays of each reused between the steps.

use std::collections::{BTreeMap, HashMap};
use std::f64::consts::PI;
use std::sync::{Arc, Mutex};

use idsp::AccuOsc;
use num_complex::Complex64 as C64;
use rayon::prelude::*;
use realfft::{ComplexToReal, RealFftPlanner, RealToComplex};

/// DAC full scale, in volts, as the firmware computes it (single precision).
const DAC_FULL_SCALE: f32 = 4.096 * 2.5;
/// Width of the raised-cosine tapers at either end of the analysis band, in octaves.
const BAND_EDGE_TAPER: f64 = 1.0 / 12.0;
/// Regularisation of the inverse filter, relative to the expected sweep PSD.
const REGULARISATION: f64 = 1e-4;
/// Magnitude floor of the minimum phase band limiting filter.
const MIN_PHASE_FLOOR: f64 = 1e-6;
/// Fraction of the impulse response window over which it is faded out.
const FADE_OUT: f64 = 0.25;
/// Margin, in octaves, around the frequencies affected by lost data.
const GAP_MARGIN: f64 = 1.0 / 24.0;
/// Passes of filling in lost data, and the relative change at which to stop.
const GAP_FILL_PASSES: usize = 8;
const GAP_FILL_TOLERANCE: f64 = 1e-3;

/// An exponential sweep, as generated by the firmware `SweptSine` source.
#[derive(Clone, Debug)]
pub struct Sweep {
    /// The firmware's oscillator parameters: the rate and the initial frequency state.
    pub source: idsp::Sweep,
    pub length: usize,
    /// Amplitude, in volts.
    pub amplitude: f64,
    /// Sample period, in seconds.
    pub sample_period: f64,
}

impl Sweep {
    pub fn new(rate: i32, state: i64, length: usize, amplitude: f64, sample_period: f64) -> Self {
        Self {
            source: idsp::Sweep::new(rate, state),
            length,
            amplitude,
            sample_period,
        }
    }

    /// Exponential growth rate of the instantaneous frequency, per sample.
    pub fn growth(&self) -> f64 {
        self.source.rate()
    }

    /// Start frequency, in cycles/sample.
    pub fn f_start(&self) -> f64 {
        self.source.state()
    }

    /// Stop frequency, in cycles/sample.
    pub fn f_stop(&self) -> f64 {
        self.f_start() * (self.growth() * self.length as f64).exp()
    }

    /// Time by which the k-th harmonic leads the fundamental, in samples.
    pub fn harmonic_delay(&self, k: f64) -> f64 {
        self.source.delay(k)
    }

    /// The excitation added to the DAC output, in volts, exactly as the firmware
    /// generates it: `idsp::AccuOsc` over `idsp::Sweep` (with its table-based sine),
    /// scaled by `signal_generator::Scaler` (computed in single precision) and
    /// truncated to the 16-bit DAC code.
    pub fn excitation(&self) -> Vec<f64> {
        let amplitude = (self.amplitude as f32 * DAC_FULL_SCALE.recip() * 2147483648f32) as i64;
        let volts_per_lsb = DAC_FULL_SCALE as f64 / 32768.0;
        AccuOsc::new(self.source.clone())
            .take(self.length)
            .map(|c| ((((c.im() as i64 * amplitude) >> 31) as i32) >> 16) as f64 * volts_per_lsb)
            .collect()
    }
}

